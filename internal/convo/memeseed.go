// SeedCommonMemes 把内置常见梗补进库 (幂等)。返回新增条数。
func SeedCommonMemes(s *Store) (int, error) {
	if s == nil {
		return 0, nil
	}
	n := 0
	for _, m := range commonMemes {
		if old, err := s.SlangByPhrase(m.Phrase); err == nil && old != nil {
			continue
		}
		if _, err := s.UpsertSlang(SlangDelta{Phrase: m.Phrase, Meaning: m.Meaning, Confidence: 0.9}, "builtin"); err != nil {
			return n, err
		}
		n++
	}
	return n, nil
}
