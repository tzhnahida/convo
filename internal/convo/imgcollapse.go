package convo

import (
	"regexp"
	"strings"
)

// ——— 重复图的「引用式」标记 ———
//
// ⚠️ **这里是 2026-10-14 那次修复的核心**，先说清它修的是什么。
//
// 用户定的口径是: 同一张图第一次给完整内容, 之后只留一句
//「这张图出现过多次, 内容往上找」指向前面那份。省 token, 且不让模型
// 以为自己看到了几十次不同的事。**口径没问题。**
//
// 但原来的实现把「第几次见到」在**入库时**就烧进了 payload ——
// 于是线上真的出现了这个:
//
//     947  群友: [图: 这张图出现过多次, 内容往上找](照片)
//     949  群友: [图: 这张图出现过多次, 内容往上找](照片)
//
// 两条**都**是引用式。它们指向的那份完整内容已经滑出历史窗口了,
// 于是「往上找」找到的是另一句「往上找」—— 指针悬空。
// 模型当时的反应是如实说 `你发的那图我这边看不清内容`。
//
// 根因不是"窗口太小", 而是**渲染时机错了**:
// "这是第几次"和"前面那份还在不在"都是**拼上下文那一刻**的属性,
// 不是入库那一刻的属性。入库时它俩都不知道。
//
// 所以现在: **入库一律存完整标记** (永远自足, 不可能悬空),
// 去重搬到拼历史时做 —— 而且只在**同一窗口内**去重,
// 于是引用**必定**指向一个真的还在上下文里的东西。
// 这是硬约束, 不是概率。

// imageMarkRE 切出「(短标) [图: 完整内容]」这一整段。
//
// ⚠️ 第 1 组是**整段** (含外层括号), 第 2 组短标, 第 3 组完整标记。
// 必须带外层组 —— 否则替换时会漏掉开头那个 `(`。
//
// ⚠️ **锚在行尾** (`$`), 而且 `.*` 是贪婪的 —— 这两条都是必需的,
// 一起解决同一个坑:
//
//	含义是 LLM 写的、图上的字是 OCR 出来的, 都可能自带 `]`。
//	我第一版写的是 `[^\]]*`, 于是
//
//	    群友1: (照片) [图: 一张带 [方括号] 的图]
//
//	只匹配到 `[图: 一张带 [方括号]` —— **半截**, 替换之后行尾剩一句
//	` 的图]`。那是把好好的句子切坏了, 比不去重糟得多。
//
//	贪婪 + 行尾锚定 → 咬到的就是**最后一个 `]`**, 即完整的那一份。
//
//	代价: 标记后面还跟着别的字 (如 `…[图: 猫] 帮我看看`) 时匹配不上,
//	于是那行**保持完整渲染**。多花几个字, 但永远是对的 ——
//	失败方向必须是"完整"这一侧, 不能是"切一半"。
var imageMarkRE = regexp.MustCompile(`(\(([^()]+)\) (\[图: .*\]))\s*$`)

// imageRepeatMark 引用式标记 —— 首次与重复**共用这一个构造点**。
func imageRepeatMark(shortTag string) string {
	return "[图: 这张图出现过多次, 内容往上找](" + shortTag + ")"
}

// ImageMarkSpan 从一行里切出 (短标, 完整标记, 整段原样)。
//
// ok=false 表示这行没有可识别的图片标记 —— 调用方必须原样保留该行。
func ImageMarkSpan(line string) (shortTag, full, whole string, ok bool) {
	m := imageMarkRE.FindStringSubmatch(line)
	if m == nil {
		return "", "", "", false
	}
	// ⚠️ **贪婪 + 行尾锚定会咬过头** —— 一行里若有两个方括号段,
	// 例如 `(照片) [图: 猫] 然后 [这样]`, 它会整段吃下去并连
	// ` 然后 [这样]` 一起替掉, 那是**静默丢字**。
	//
	// ⚠️ **贪婪会咬过头, 这里要挡住** —— RE2 没有负向断言, 只能自己判。
	//
	// 两种行长得几乎一样, 但一个该收一个不该收:
	//
	//   A  (照片) [图: 一张带 [方括号] 的图]      ← 括号是**嵌套**的, 整段是对的
	//   B  (照片) [图: 猫] 然后 [这样]            ← 两个**并列**段, 贪婪把后面也吃了
	//
	// B 若照收, ` 然后 [这样]` 就**静默消失**了 —— 丢字比不去重严重得多。
	//
	// 判据是**外层括号里的东西是不是配平的**:
	//   A 的内层 `图: 一张带 [方括号] 的图` → 先 `[` 后 `]`, 从不为负 ✓
	//   B 的内层 `图: 猫] 然后 [这样`       → 一上来就撞 `]`, 立刻为负 ✗
	//
	// 真实 payload 里标记永远在**行尾**, 所以 A 这种嵌套是会出现的
	// (含义是 LLM 写的、`「」`里是 OCR 的字, 谁都可能带方括号)。
	// B 目前不会出现 —— 但"不会出现"不是判据, 这个检查才是。
	if !bracketBalanced(m[3]) {
		return "", "", "", false
	}
	return m[2], m[3], m[1], true
}

// bracketBalanced 判断一个以 `[` 开头、`]` 结尾的串, 去掉最外层之后
// 内部是不是**配平**的 (没有任何一个 `]` 先于它的 `[` 出现)。
//
// 不配平 = 这个 `]` 不是我们要的那个 —— 贪婪咬过头了。
func bracketBalanced(s string) bool {
	if len(s) < 2 || s[0] != '[' || s[len(s)-1] != ']' {
		return false
	}
	depth := 0
	for _, r := range s[1 : len(s)-1] {
		switch r {
		case '[':
			depth++
		case ']':
			depth--
			if depth < 0 {
				return false
			}
		}
	}
	return true
}

// CollapseRepeatedImageMarks 对**按时间顺序**排好的一组行做图片去重。
//
// 同一张图的第 1 次保留完整标记, 第 2 次及以后换成引用式。
// 判同的依据是**完整标记本身逐字节相等** —— 同一张图的标签是同一份
// (标签按 md5 缓存), 所以这比拿 md5 比对更省事, 而且不需要改表。
//
// ⚠️ 不许原地改入参: 调用方持有的切片可能还要用。
func CollapseRepeatedImageMarks(lines []string) []string {
	out := make([]string, len(lines))
	copy(out, lines)
	seen := make(map[string]bool, 8)
	for i, line := range out {
		shortTag, full, whole, ok := ImageMarkSpan(line)
		if !ok {
			continue
		}
		if seen[full] {
			// 同一个完整标记前面已经有过 → 这行改成指针。
			// ⚠️ 用整段原样替换 (且只换第一处), 不做任何下标算术 ——
			// 那段算术我第一版就写错了: 把开头的 `(` 留在了行里。
			out[i] = strings.Replace(line, whole, imageRepeatMark(shortTag), 1)
			continue
		}
		seen[full] = true
	}
	return out
}
