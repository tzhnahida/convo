// seedWord represents a word in a seed JSON file.
type seedWord struct {
	Word    string `json:"word"`
	Reading string `json:"reading"`
	Meaning string `json:"meaning"`
	POS     string `json:"pos"`
}

// loadSeedWords reads seed words from configs/languages/seeds/<lang>.json and
// inserts any that do not already exist in the database. Returns the number of
// newly inserted words.
func loadSeedWords(s *Server, lang string) (int, error) {
	path := filepath.Join(s.ConfigDir, "languages", "seeds", lang+".json")
	data, err := os.ReadFile(path)
	if err != nil {
		return 0, fmt.Errorf("read seed file %s: %w", path, err)
	}

	var seeds []seedWord
	if err := json.Unmarshal(data, &seeds); err != nil {
		return 0, fmt.Errorf("parse seed file %s: %w", path, err)
	}

	inserted := 0
	for _, sw := range seeds {
		if sw.Word == "" {
			continue
		}
		exists, err := s.DB.WordExists(lang, sw.Word)
		if err != nil {
			return inserted, fmt.Errorf("check word exists: %w", err)
		}
		if exists {
			continue
		}
		_, err = s.DB.InsertWord(&db.Word{
			Word:     sw.Word,
			Reading:  sw.Reading,
			Meaning:  sw.Meaning,
			POS:      sw.POS,
			Language: lang,
			Source:   "seed",
			Status:   "active",
		})
		if err != nil {
			return inserted, fmt.Errorf("insert seed word %q: %w", sw.Word, err)
		}
		inserted++
	}
	return inserted, nil
}

// EnsureBootstrap checks whether the given language has any words or grammar
// points in the database; if not, it loads seed data from the seed file and
// language config. It is safe to call multiple times 閳?duplicate inserts are
// prevented by existence checks.
func (s *Server) EnsureBootstrap(lang string) {
	if s.Mock {
		return
	}
	if s.DB == nil {
		return
	}
	if lang == "" {
		// No language selected yet — user hasn't completed onboarding.
		// Bootstrap will run when language is set via PUT /api/v1/config.
		s.markBootstrapDone()
		return
	}

	log.Info("bootstrap", "start: lang=%s", lang)

	// Check word count.
	_, total, err := s.DB.ListWords(lang, 1, 0)
	if err != nil {
		log.Error("bootstrap", "list words: %v", err)
		s.markBootstrapDone()
		return
	}

	if total == 0 {
		if s.AI() != nil && s.DictProvider != nil {
			// AI available 閳?generate initial words from plan direction
			expandCount, extraCtx := s.planExpandParams(lang)
			if expandCount <= 0 {
				expandCount = s.Config.App.DailyTarget
			}
			log.Debug("bootstrap", "generating initial words via AI for %s", lang)
			if !s.tryStartExpanding() {
				log.Debug("bootstrap", "another expansion already running, marking done")
				s.markBootstrapDone()
			} else {
				go func() {
					defer s.stopExpanding()
					verified, pending, err := s.expandWords(context.Background(), lang, expandCount, extraCtx)
					if err != nil {
						log.Error("bootstrap", "AI expansion failed: %v", err)
						loadSeedWords(s, lang)
					} else {
						log.Debug("bootstrap", "AI generated %d verified + %d pending words", verified, pending)
						go s.fillMissingDetails(lang)
					}
					gc := 0
					if langHasGrammarType(lang, s.Config) {
						var gErr error
						gc, gErr = s.expandGrammar(context.Background(), lang, 3)
						if gErr != nil {
							log.Error("bootstrap", "grammar expansion failed: %v", gErr)
						} else {
							log.Debug("bootstrap", "AI generated %d grammar points", gc)
						}
					}
					log.Info("bootstrap", "done: lang=%s words=%d grammar=%d", lang, verified+pending, gc)
					s.markBootstrapDone()
				}()
			}
		} else {
			n, err := loadSeedWords(s, lang)
			if err != nil {
				log.Error("bootstrap", "load seed words: %v", err)
			} else if n > 0 {
				log.Debug("bootstrap", "loaded %d seed words for %s", n, lang)
			}
			log.Info("bootstrap", "done: lang=%s words=%d grammar=0", lang, n)
			s.markBootstrapDone()
		}
	} else {
		log.Info("bootstrap", "done: lang=%s words=%d grammar=0", lang, total)
		s.markBootstrapDone()
	}

	// Fill missing detail fields for words that lack them (runs in background)
	if s.AI() != nil && s.DictProvider != nil {
		go s.fillMissingDetails(lang)
	}

	// Grammar points are generated by AI via expandGrammar (same lifecycle as words).
	// No config-loaded grammar seeds 閳?ja.yaml tells AI HOW, not WHAT.
}

// fillMissingDetails fills missing reading/meaning/detail for words in the
// background. For words lacking reading/meaning, it tries dict lookup first;
// if found, AI generates the detail JSON. Covers both bootstrap leftovers and
// pending-review words that the earlier batch retry missed.
func (s *Server) fillMissingDetails(lang string) {
	if s.AI() == nil || s.DB == nil {
		return
	}
	words, _, err := s.DB.ListWords(lang, 100, 0)
	if err != nil {
		return
	}
	_, level, _, _ := s.expandLangContext(lang)
	filled := 0
	for _, w := range words {
		// Skip words that are already fully populated
		if w.Meaning != "" && w.Detail != "" && w.Detail != "{}" && len(w.Detail) > 10 {
			continue
		}

		// If missing reading/meaning, try dict lookup first
		if w.Reading == "" || w.Meaning == "" {
			if s.DictProvider != nil {
				ctx2, cancel2 := context.WithTimeout(context.Background(), 10*time.Second)
				entry := s.lookupDict(ctx2, w.Word)
				cancel2()
				if entry != nil {
					if w.Reading == "" {
						w.Reading = entry.Reading
					}
					if w.Meaning == "" {
						w.Meaning = entry.Meaning
					}
					if w.POS == "" {
						w.POS = entry.POS
					}
					if w.Level == "" {
						w.Level = entry.Level
					}
				}
			}
			// Still no meaning after dict → can't generate useful detail
			if w.Meaning == "" {
				continue
			}
		}

		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		aiDetail := s.generateDetail(ctx, w.Word, w.Reading, w.Meaning, w.POS, level, lang)
		cancel()
		if aiDetail == "" || aiDetail == "{}" {
			continue
		}
		if w.Detail != "" && w.Detail != "{}" {
			aiDetail = mergeJSON(w.Detail, aiDetail)
		}
		w.Detail = aiDetail
		if lv := extractFieldFromDetail(aiDetail, "level"); lv != "" && w.Level == "" {
			w.Level = lv
		}
		if s.DB.UpdateWord(w) == nil {
			filled++
		}
		time.Sleep(500 * time.Millisecond)
	}
	if filled > 0 {
		log.Debug("bootstrap", "filled detail for %d words in %s", filled, lang)
	}
}
